function latexHeader(venueFormat: string, title: string, abstract: string): string {
  return (
    "% Auto-generated by RSI (ScientistTwo loop, Pi extension)\n" +
    `% venue format: ${venueFormat}\n` +
    "\\documentclass{article}\n" +
    "\\usepackage{iclr2025_conference,times}\n" +
    `\\title{${title}}\n` +
    "\\begin{document}\n" +
    "\\maketitle\n" +
    "\\begin{abstract}\n" +
    `${abstract}\n` +
    "\\end{abstract}\n"
  );
}

function escLatex(value: string): string {
  return value
    .replace(/\\/g, "")
    .replace(/&/g, "\\&")
    .replace(/%/g, "\\%")
    .replace(/_/g, "\\_");
}

function exportLatex(
  ctx: { store: { artifact(rel: string): string } },
  manuscriptId: string,
  title: string,
  sections: Record<string, string>,
  claims: Claim[],
  venueFormat: string,
  round: number,
): string {
  const safeTitle = escLatex(title);
  const body: string[] = [latexHeader(venueFormat, safeTitle, sections.abstract ?? "")];
  for (const [name, text] of Object.entries(sections)) {
    if (name === "abstract" || !text.trim()) continue;
    const heading = name.replace(/_/g, " ").replace(/\b\w/g, (ch) => ch.toUpperCase());
    body.push(`\\section{${heading}}\n${text}\n`);
  }
  if (claims.length) {
    const rows = claims
      .filter((claim) => claim.metric)
      .map((claim) => `${claim.metric} & ${claim.value} & ${claim.text.slice(0, 120)} \\\\`)
      .join("\n");
    body.push(
      "\\section{Claim--evidence ledger}\n\\begin{tabular}{lll}\nMetric & Value & Claim \\\\\n" +
        `${rows}\n\\end{tabular}\n`,
    );
  }
  body.push("\\end{document}\n");
  const file = ctx.store.artifact(`${manuscriptId}-r${round}.tex`);
  fs.writeFileSync(file, body.join("\n"), "utf8");
  return file;
}

function claimSupported(claim: Claim, ledger: Record<string, number>): boolean {
  const measured = ledger[claim.metric];
  return Boolean(
    claim.text.trim() &&
      claim.metric.trim() &&
      claim.evidence_ref.trim() &&
      finite(claim.value) &&
      finite(measured) &&
      Math.abs(claim.value - measured) <= 1e-9,
  );
}

function mentions(text: string, name: string): boolean {
  if (!name.trim()) return false;
  const escaped = name.trim().replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?<!\\w)${escaped}(?!\\w)`, "i").test(text);
}

/** Deterministic §3.5/§3.6 structural and evidence violations. */
export function validateManuscript(manuscript: Manuscript, config: Config, problem: Problem): string[] {
  const violations: string[] = [];
  for (const section of config.requiredSections) {
    if (!(section in manuscript.sections)) violations.push(`Missing required section: ${section}`);
    else if (!manuscript.sections[section].trim()) violations.push(`Empty required section: ${section}`);
  }
  if (manuscript.format !== config.venueFormat) {
    violations.push(`Manuscript format must be ${config.venueFormat}`);
  }
  const method = manuscript.sections.method ?? "";
  if (!/\bbaseline\b/i.test(method)) {
    violations.push("Method must summarize the change versus the human baseline");
  }
  const text = [
    manuscript.title,
    manuscript.abstract,
    ...Object.values(manuscript.sections),
    ...manuscript.claims.map((claim) => claim.text),
  ].join("\n");
  if (
    problem.directions.length &&
    !problem.directions.some((direction) =>
      [direction.id, direction.title, ...direction.keywords].some((name) => mentions(text, name)),
    )
  ) {
    violations.push("Manuscript is missing a guidance direction mention (ID, title or keyword)");
  }
  const ledger = manuscript.evidence_ledger;
  if (!Object.keys(ledger).length) violations.push("no evidence ledger");
  manuscript.claims.forEach((claim, index) => {
    const prefix = `Claim ${index + 1}`;
    if (!claim.text.trim()) violations.push(`${prefix} has empty text`);
    if (!claim.metric.trim()) violations.push(`${prefix} has an empty metric`);
    if (!finite(claim.value)) violations.push(`${prefix} has an empty or non-finite numeric value`);
    if (!claim.evidence_ref.trim()) violations.push(`${prefix} has an empty evidence_ref`);
    if (Object.keys(ledger).length) {
      const measured = ledger[claim.metric];
      if (!finite(measured)) {
        violations.push(`${prefix} metric '${claim.metric}' is absent from provided evidence`);
      } else if (finite(claim.value) && Math.abs(claim.value - measured) > 1e-9) {
        violations.push(`${prefix} value does not match its measured evidence`);
      }
    }
  });
  return violations;
}

function measurements(evidence: Evidence): Record<string, number> {
  const out: Record<string, number> = {};
  if (!evidenceOk(evidence)) return out;
  for (const [name, value] of Object.entries(evidence.metrics)) if (finite(value)) out[name] = value;
  return out;
}

export class InitialDrafter extends BaseAgent {
  readonly NAME = "initial_drafter";
  readonly task = "write.draft";
  readonly role = "default";

  async draft(opts: {
    idea: Idea;
    best: Evidence;
    ablations: AblationResult[];
    round?: number;
    reviewerFeedback?: string;
  }): Promise<Manuscript> {
    const round = opts.round ?? 0;
    const reviewerFeedback = opts.reviewerFeedback ?? "";
    const ledger = measurements(opts.best);
    const refs: Record<string, string> = {};
    for (const metric of Object.keys(ledger)) refs[metric] = opts.best.label.trim() || `${opts.best.scope}:${opts.best.idea_id}`;
    for (const result of opts.ablations) {
      const metrics = result.evidence ? measurements(result.evidence) : result.metrics;
      if (!result.ok) continue;
      for (const [metric, value] of Object.entries(metrics)) {
        if (!finite(value)) continue;
        const key = `ablation:${result.plan_id}:${metric}`;
        ledger[key] = value;
        refs[key] = `ablation:${result.plan_id}`;
      }
    }

    const output = await this.ask(DraftOutput, {
      user:
        "Draft a complete PaperOrchestra-style conference manuscript in the requested format. " +
        "Fill every required section. In method explain which guidance directions the idea " +
        "advances and the algorithmic diff against the human baseline. Use reproduced baseline " +
        "measurements, never paper-reported scores, for comparisons. Each Claim needs text, a " +
        "metric key from evidence_ledger, its exact finite value and a non-empty evidence_ref. " +
        "No measured metric means no claim. Include full-set and component-ablation evidence; " +
        "disclose failed/absent experiments. Do not invent citations or findings.\n" +
        guidance(this.ctx) +
        "\n" +
        stableString({
          idea: opts.idea,
          best: opts.best,
          ablations: opts.ablations,
          evidence_ledger: ledger,
          evidence_refs: refs,
          required_sections: this.ctx.config.requiredSections,
          format: this.ctx.config.venueFormat,
          reviewer_feedback: reviewerFeedback,
        }),
      meta: { idea_id: opts.idea.id, round },
    });

    const directions = this.ctx.problem.directions.filter((direction) =>
      opts.idea.direction_ids.includes(direction.id),
    );
    let directionText = directions.length
      ? `This idea advances guidance direction(s): ${directions.map((d) => `${d.id}: ${d.title}`).join("; ")}.`
      : "";
    if (!directions.length && this.ctx.problem.directions.length) {
      directionText =
        "Guidance context (alignment has not yet been established): " +
        this.ctx.problem.directions.map((d) => `${d.id}: ${d.title}`).join("; ") +
        ".";
    }
    const methodSummary = (
      `Change versus the human baseline (${this.ctx.problem.source_paper || "reproduced reference method"}): ` +
      `${opts.idea.mechanism || opts.idea.hypothesis}. Hypothesis: ${opts.idea.hypothesis}. ${directionText}`
    ).trim();
    const measurementText =
      Object.entries(ledger)
        .map(([metric, value]) => `${metric} = ${value} [${refs[metric]}]`)
        .join("; ") ||
      "No successful measurements are available; no empirical improvement is established.";
    const ablationText =
      opts.ablations
        .map(
          (result) =>
            `${result.component || result.plan_id} [${result.plan_id}]: ` +
            (result.ok && (!result.evidence || evidenceOk(result.evidence))
              ? stableString(result.evidence ? result.evidence.metrics : result.metrics)
              : "execution failed; attribution unverified"),
        )
        .join("; ") || "No component-ablation results are available; attribution remains unverified.";

    const defaults: Record<string, string> = {
      abstract: `We study ${this.ctx.problem.statement} Hypothesis: ${opts.idea.hypothesis}. ${measurementText}`,
      introduction: `Research problem: ${this.ctx.problem.statement} Proposed mechanism: ${opts.idea.mechanism || opts.idea.hypothesis}.`,
      related_work: `Human baseline: ${this.ctx.problem.source_paper || "the supplied reference method"}. No additional references were verified.`,
      method: methodSummary,
      experiments: `Full-set measurements and evidence references: ${measurementText}`,
      ablation: `Component interventions and measured outcomes: ${ablationText}`,
      conclusion: `The proposed mechanism is ${opts.idea.mechanism || opts.idea.hypothesis}; conclusions are limited to supplied measurements.`,
    };
    const sections = { ...output.sections };
    for (const section of this.ctx.config.requiredSections) {
      if (!(sections[section] ?? "").trim()) {
        sections[section] =
          defaults[section] ?? `${section}: evidence coverage is limited to the supplied experiments.`;
      }
    }
    if ((sections.method ?? "").trim() !== methodSummary) {
      sections.method = `${sections.method ?? ""}\n${methodSummary}`.trim();
    }
    if (reviewerFeedback.trim()) {
      sections.method += `\nEmpirical/algorithmic revision requested by meta-review: ${reviewerFeedback.trim()}`;
    }
    let claims = output.claims.filter((claim) => claimSupported(claim, ledger));
    if (!claims.length) {
      claims = Object.entries(ledger).map(([metric, value]) => ({
        text: `The measured ${metric} is ${value}.`,
        metric,
        value,
        evidence_ref: refs[metric],
      }));
    }
    const title = output.title.trim() || `${opts.idea.mechanism || opts.idea.hypothesis}: an empirical study`;
    const id = output.id.trim() || `${opts.idea.id}-paper-${round}`;
    const manuscript = makeManuscript({
      id,
      title,
      abstract: sections.abstract ?? output.abstract,
      sections,
      claims,
      evidence_ledger: ledger,
      format: this.ctx.config.venueFormat,
      round,
      latex_path: "",
    });
    manuscript.latex_path = exportLatex(
      this.ctx,
      `${opts.idea.id}-paper-${round}`,
      title,
      sections,
      claims,
      this.ctx.config.venueFormat,
      round,
    );
    this.log("manuscript_validation", {
      id: manuscript.id,
      violations: validateManuscript(manuscript, this.ctx.config, this.ctx.problem),
    });
    return manuscript;
  }
}

export class PaperEnhancer extends BaseAgent {
  readonly NAME = "paper_enhancer";
  readonly task = "write.enhance";
  readonly role = "draft_enhancer";

  async enhance(opts: {
    manuscript: Manuscript;
    review: Review;
    rebuttal: Evidence[];
    /** Meta-review / area-chair critique: revise the paper, never re-draft it. */
    feedback?: string;
  }): Promise<Manuscript> {
    const feedback = (opts.feedback ?? "").trim();
    const supplementary: Record<string, number> = {};
    for (const evidence of opts.rebuttal) Object.assign(supplementary, measurements(evidence));
    const ledger = { ...opts.manuscript.evidence_ledger, ...supplementary };

    const output = await this.ask(DraftOutput, {
      user:
        "Enhance the CURRENT manuscript using its review and supplied supplementary evidence only. " +
        "Preserve scientific identity and required sections. New claims are permitted ONLY for " +
        "metrics and exact values measured in successful rebuttal evidence, with non-empty " +
        "evidence_ref. Drop or downgrade unsupported claims. Do not invent experimental findings, " +
        "rewrite the core method, or treat reviewer suggestions as results. " +
        "When meta-review feedback is supplied, revise THIS manuscript to answer it " +
        "(claims, framing, limitations, reported evidence); do not start a new paper.\n" +
        (feedback ? `Meta-review feedback to answer: ${feedback}\n` : "") +
        guidance(this.ctx) +
        "\n" +
        stableString({
          manuscript: opts.manuscript,
          review: opts.review,
          rebuttal: opts.rebuttal,
          rebuttal_metrics: supplementary,
          meta_feedback: feedback,
        }),
      meta: { manuscript_id: opts.manuscript.id, round: opts.manuscript.round + 1 },
    });

    const oldClaims = opts.manuscript.claims.filter((claim) =>
      claimSupported(claim, opts.manuscript.evidence_ledger),
    );
    const oldSignatures = new Set(
      oldClaims.map((claim) => `${claim.metric}|${claim.value}|${claim.evidence_ref}`),
    );
    const claims: Claim[] = [];
    for (const claim of output.claims.length ? output.claims : oldClaims) {
      if (!claimSupported(claim, ledger)) continue;
      const signature = `${claim.metric}|${claim.value}|${claim.evidence_ref}`;
      if (oldSignatures.has(signature) || claimSupported(claim, supplementary)) claims.push(claim);
    }
    const sections = { ...opts.manuscript.sections };
    for (const [key, text] of Object.entries(output.sections)) {
      if (text.trim()) sections[key] = text;
    }
    if ("method" in opts.manuscript.sections) sections.method = opts.manuscript.sections.method;
    if (Object.keys(supplementary).length) {
      sections.rebuttal = `Supplementary evidence addressing reviewer queries: ${stableString(supplementary)}`;
    }
    const title = output.title.trim() || opts.manuscript.title;
    return makeManuscript({
      id: opts.manuscript.id,
      title,
      abstract: sections.abstract ?? opts.manuscript.abstract,
      sections,
      claims,
      evidence_ledger: ledger,
      format: this.ctx.config.venueFormat,
      round: opts.manuscript.round + 1,
      latex_path: exportLatex(
        this.ctx,
        opts.manuscript.id,
        title,
        sections,
        claims,
        this.ctx.config.venueFormat,
        opts.manuscript.round + 1,
      ),
    });
  }
}
