"""§3.5 — full manuscripts and review-driven, evidence-bound enhancement.

Structural validation is deterministic, not proof of scientific novelty or
conference readiness. The canonical audit surface is Manuscript.evidence_ledger.
"""

from __future__ import annotations

import json
import math
import re
from typing import Any

from ..config import ScientistTwoConfig
from ..types import AblationResult, Claim, Evidence, Idea, Manuscript, Problem, Review
from .base import BaseAgent

__all__ = ["InitialDrafter", "PaperEnhancer", "validate_manuscript"]


class _DraftOutput(Manuscript):
    """Default-constructible LLM schema despite required Manuscript.id."""

    id: str = ""


def _finite(value: Any) -> bool:
    return isinstance(value, (float, int)) and not isinstance(value, bool) and math.isfinite(value)


_LATEX_HEADER = (
    "% Auto-generated by ScientistTwo (reimplementation of arXiv:2609.19644)\n"
    "% venue format: {format}\n"
    "\\documentclass{{article}}\n"
    "\\usepackage{{iclr2025_conference,times}}\n"
    "\\title{{{title}}}\n"
    "\\begin{{document}}\n"
    "\\maketitle\n"
    "\\begin{{abstract}}\n"
    "{abstract}\n"
    "\\end{{abstract}}\n"
)


def _export_latex(
    ctx: Any, manuscript_id: str, title: str, sections: dict[str, str], claims: list[Claim],
    venue_format: str, round_index: int,
) -> str:
    """Write the manuscript as LaTeX and return its path (§3.5, ICLR 2025 template)."""

    safe_title = title.replace("\\", "").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
    body = [_LATEX_HEADER.format(
        format=venue_format,
        title=safe_title,
        abstract=sections.get("abstract", ""),
    )]
    for name, text in sections.items():
        if name == "abstract" or not text.strip():
            continue
        heading = name.replace("_", " ").title()
        body.append(f"\\section{{{heading}}}\n{text}\n")
    if claims:
        rows = "\n".join(
            f"{claim.metric} & {claim.value} & {claim.text[:120]} \\\\"
            for claim in claims if claim.metric
        )
        body.append(
            "\\section{Claim--evidence ledger}\n\\begin{tabular}{lll}\nMetric & Value & Claim \\\\\n"
            f"{rows}\n\\end{{tabular}}\n"
        )
    body.append("\\end{document}\n")
    path = ctx.store.artifact(f"{manuscript_id}-r{round_index}.tex")
    path.write_text("\n".join(body), encoding="utf-8")
    return str(path)


def _claim_supported(claim: Claim, ledger: dict[str, float]) -> bool:
    measured = ledger.get(claim.metric)
    return bool(
        claim.text.strip() and claim.metric.strip() and claim.evidence_ref.strip()
        and _finite(claim.value) and _finite(measured)
        and abs(float(claim.value) - float(measured)) <= 1e-9
    )


def _mentions(text: str, name: str) -> bool:
    return bool(name.strip() and re.search(r"(?<!\w)" + re.escape(name.strip()) + r"(?!\w)", text, re.IGNORECASE))


def validate_manuscript(
    manuscript: Manuscript,
    config: ScientistTwoConfig,
    problem: Problem,
) -> list[str]:
    """Return ordered §3.5/§3.6 structural and evidence violations, purely.

    The optional ledger is authoritative when present: every claim metric must
    exist and agree to absolute tolerance 1e-9. An absent/empty ledger emits
    ``no evidence ledger`` without declaring otherwise numeric claims false.
    Direction IDs, titles or keywords may appear anywhere in the manuscript.
    """

    violations: list[str] = []
    for section in config.required_sections:
        if section not in manuscript.sections:
            violations.append(f"Missing required section: {section}")
        elif not manuscript.sections[section].strip():
            violations.append(f"Empty required section: {section}")
    if manuscript.format != config.venue_format:
        violations.append(f"Manuscript format must be {config.venue_format}")
    method = manuscript.sections.get("method", "")
    if not re.search(r"\bbaseline\b", method, re.IGNORECASE):
        violations.append("Method must summarize the change versus the human baseline")
    text = "\n".join([manuscript.title, manuscript.abstract, *manuscript.sections.values(),
                      *(claim.text for claim in manuscript.claims)])
    if problem.directions and not any(
        _mentions(text, name)
        for direction in problem.directions
        for name in [direction.id, direction.title, *direction.keywords]
    ):
        violations.append("Manuscript is missing a guidance direction mention (ID, title or keyword)")
    ledger = manuscript.evidence_ledger
    if not ledger:
        violations.append("no evidence ledger")
    for index, claim in enumerate(manuscript.claims, start=1):
        prefix = f"Claim {index}"
        if not claim.text.strip():
            violations.append(f"{prefix} has empty text")
        if not claim.metric.strip():
            violations.append(f"{prefix} has an empty metric")
        if not _finite(claim.value):
            violations.append(f"{prefix} has an empty or non-finite numeric value")
        if not claim.evidence_ref.strip():
            violations.append(f"{prefix} has an empty evidence_ref")
        if ledger:
            measured = ledger.get(claim.metric)
            if not _finite(measured):
                violations.append(f"{prefix} metric '{claim.metric}' is absent from provided evidence")
            elif _finite(claim.value) and abs(float(claim.value) - float(measured)) > 1e-9:
                violations.append(f"{prefix} value does not match its measured evidence")
    return violations


def _measurements(evidence: Evidence) -> dict[str, float]:
    return {name: value for name, value in evidence.metrics.items() if evidence.ok() and _finite(value)}


class InitialDrafter(BaseAgent):
    NAME = "initial_drafter"
    task = "write.draft"
    role = "default"

    async def draft(
        self,
        *,
        idea: Idea,
        best: Evidence,
        ablations: list[AblationResult],
        round: int = 0,
        reviewer_feedback: str = "",
    ) -> Manuscript:
        """Synthesize idea, full-set evidence and ablations in venue format (§3.5)."""

        ledger = _measurements(best)
        refs = {metric: best.label.strip() or f"{best.scope.value}:{best.idea_id}" for metric in ledger}
        # CONTRACT-GAP: a flat metric->value ledger cannot represent the same
        # metric across several experiments. Qualify ablation metrics by plan ID
        # so they cannot silently overwrite full-set measurements.
        for result in ablations:
            metrics = _measurements(result.evidence) if result.evidence is not None else result.metrics
            if result.ok:
                for metric, value in metrics.items():
                    if _finite(value):
                        key = f"ablation:{result.plan_id}:{metric}"
                        ledger[key] = value
                        refs[key] = f"ablation:{result.plan_id}"
        output = await self.ask(
            _DraftOutput,
            user=(
                "Draft a complete PaperOrchestra-style conference manuscript in the requested format. "
                "Fill every required section. In method explain which guidance directions the idea "
                "advances and the algorithmic diff against the human baseline. Use reproduced baseline "
                "measurements, never paper-reported scores, for comparisons. Each Claim needs text, a "
                "metric key from evidence_ledger, its exact finite value and a non-empty evidence_ref. "
                "No measured metric means no claim. Include full-set and component-ablation evidence; "
                "disclose failed/absent experiments. Do not invent citations or findings.\n"
                + self.ctx.guidance() + "\n"
                + json.dumps({"idea": idea.model_dump(mode="json"), "best": best.model_dump(mode="json"),
                              "ablations": [result.model_dump(mode="json") for result in ablations],
                              "evidence_ledger": ledger, "evidence_refs": refs,
                              "required_sections": self.ctx.config.required_sections,
                              "format": self.ctx.config.venue_format,
                              "reviewer_feedback": reviewer_feedback}, sort_keys=True)
            ),
            idea_id=idea.id,
            round=round,
        )
        directions = [direction for direction in self.ctx.problem.directions if direction.id in idea.direction_ids]
        direction_text = "; ".join(f"{direction.id}: {direction.title}" for direction in directions)
        if direction_text:
            direction_text = f"This idea advances guidance direction(s): {direction_text}."
        elif self.ctx.problem.directions:
            direction_text = (
                "Guidance context (alignment has not yet been established): "
                + "; ".join(f"{direction.id}: {direction.title}" for direction in self.ctx.problem.directions) + "."
            )
        method_summary = (
            f"Change versus the human baseline ({self.ctx.problem.source_paper or 'reproduced reference method'}): "
            f"{idea.mechanism or idea.hypothesis}. Hypothesis: {idea.hypothesis}. {direction_text}"
        ).strip()
        measurement_text = "; ".join(f"{metric} = {value} [{refs[metric]}]" for metric, value in ledger.items())
        measurement_text = measurement_text or "No successful measurements are available; no empirical improvement is established."
        ablation_text = "; ".join(
            f"{result.component or result.plan_id} [{result.plan_id}]: "
            + (json.dumps(result.evidence.metrics if result.evidence is not None else result.metrics, sort_keys=True)
               if result.ok and (result.evidence is None or result.evidence.ok()) else "execution failed; attribution unverified")
            for result in ablations
        ) or "No component-ablation results are available; attribution remains unverified."
        defaults = {
            "abstract": f"We study {self.ctx.problem.statement} Hypothesis: {idea.hypothesis}. {measurement_text}",
            "introduction": f"Research problem: {self.ctx.problem.statement} Proposed mechanism: {idea.mechanism or idea.hypothesis}.",
            "related_work": f"Human baseline: {self.ctx.problem.source_paper or 'the supplied reference method'}. No additional references were verified.",
            "method": method_summary,
            "experiments": f"Full-set measurements and evidence references: {measurement_text}",
            "ablation": f"Component interventions and measured outcomes: {ablation_text}",
            "conclusion": f"The proposed mechanism is {idea.mechanism or idea.hypothesis}; conclusions are limited to supplied measurements.",
        }
        sections = dict(output.sections)
        for section in self.ctx.config.required_sections:
            if not sections.get(section, "").strip():
                sections[section] = defaults.get(section, f"{section}: evidence coverage is limited to the supplied experiments.")
        if sections.get("method", "").strip() != method_summary:
            sections["method"] = (sections.get("method", "") + "\n" + method_summary).strip()
        if reviewer_feedback.strip():
            sections["method"] += f"\nEmpirical/algorithmic revision requested by meta-review: {reviewer_feedback.strip()}"
        claims = [claim for claim in output.claims if _claim_supported(claim, ledger)]
        if not claims:
            claims = [Claim(text=f"The measured {metric} is {value}.", metric=metric, value=value, evidence_ref=refs[metric])
                      for metric, value in ledger.items()]
        manuscript = Manuscript(
            id=output.id.strip() or f"{idea.id}-paper-{round}",
            title=output.title.strip() or f"{idea.mechanism or idea.hypothesis}: an empirical study",
            abstract=sections.get("abstract", output.abstract), sections=sections, claims=claims,
            evidence_ledger=ledger, format=self.ctx.config.venue_format, round=round,
            latex_path=_export_latex(self.ctx, f"{idea.id}-paper-{round}",
                                     output.title.strip() or f"{idea.mechanism or idea.hypothesis}: an empirical study",
                                     sections, claims, self.ctx.config.venue_format, round),
        )
        self.log("manuscript_validation", {"id": manuscript.id,
                                          "violations": validate_manuscript(manuscript, self.ctx.config, self.ctx.problem)})
        return manuscript


class PaperEnhancer(BaseAgent):
    NAME = "paper_enhancer"
    task = "write.enhance"
    role = "draft_enhancer"

    async def enhance(
        self,
        *,
        manuscript: Manuscript,
        review: Review,
        rebuttal: list[Evidence],
    ) -> Manuscript:
        """Revise using review and measured rebuttal evidence only (§3.5).

        Existing supported measurements may be restated; every newly introduced
        metric/value must resolve to successful rebuttal evidence. Model-supplied
        ledgers are ignored, so unsupported claims cannot authorize themselves.
        """

        supplementary: dict[str, float] = {}
        for evidence in rebuttal:
            supplementary.update(_measurements(evidence))
        ledger = {**manuscript.evidence_ledger, **supplementary}
        output = await self.ask(
            _DraftOutput,
            user=(
                "Enhance the CURRENT manuscript using its review and supplied supplementary evidence only. "
                "Preserve scientific identity and required sections. New claims are permitted ONLY for "
                "metrics and exact values measured in successful rebuttal evidence, with non-empty "
                "evidence_ref. Drop or downgrade unsupported claims. Do not invent experimental findings, "
                "rewrite the core method, or treat reviewer suggestions as results.\n"
                + self.ctx.guidance() + "\n"
                + json.dumps({"manuscript": manuscript.model_dump(mode="json"),
                              "review": review.model_dump(mode="json"),
                              "rebuttal": [evidence.model_dump(mode="json") for evidence in rebuttal],
                              "rebuttal_metrics": supplementary}, sort_keys=True)
            ),
            manuscript_id=manuscript.id,
            round=manuscript.round + 1,
        )
        old_claims = [claim for claim in manuscript.claims if _claim_supported(claim, manuscript.evidence_ledger)]
        old_signatures = {(claim.metric, claim.value, claim.evidence_ref) for claim in old_claims}
        claims: list[Claim] = []
        for claim in output.claims or old_claims:
            if not _claim_supported(claim, ledger):
                continue
            if (claim.metric, claim.value, claim.evidence_ref) in old_signatures or _claim_supported(claim, supplementary):
                claims.append(claim)
        # Deliberately no "resurrect the old claims" fallback: if the revision
        # produced nothing verifiable, the manuscript loses those claims and the
        # §3.5/§3.6 gates see a weaker paper. Dropping can only lower the
        # acceptance gate; restoring could launder unsupported science.
        sections = dict(manuscript.sections)
        sections.update({key: text for key, text in output.sections.items() if text.strip()})
        # Supplementary experiments cannot erase the algorithm's audited
        # baseline/guidance identity or silently substitute a new algorithm.
        if "method" in manuscript.sections:
            sections["method"] = manuscript.sections["method"]
        if supplementary:
            sections["rebuttal"] = "Supplementary evidence addressing reviewer queries: " + json.dumps(supplementary, sort_keys=True)
        return Manuscript(
            id=manuscript.id, title=output.title.strip() or manuscript.title,
            abstract=sections.get("abstract", manuscript.abstract), sections=sections, claims=claims,
            evidence_ledger=ledger, format=self.ctx.config.venue_format, round=manuscript.round + 1,
            latex_path=_export_latex(self.ctx, manuscript.id, output.title.strip() or manuscript.title,
                                     sections, claims, self.ctx.config.venue_format, manuscript.round + 1),
        )
